/** Four visually distinct levels, separated by colour AND icon AND wording -
 *  a reader skimming the arrow should not have to hover anything to know which
 *  one they are looking at.
 *
 *  The wording is deliberate. A precedent is something the evidence index was
 *  found to contain AFTER the route was proposed; it is never the source the
 *  route came from. "Direct" vs "Similar" is the distinction that carries the
 *  whole product-trust burden, so it is in the label itself, not a tooltip. */
const EVIDENCE: Record<
  EvidenceLevel,
  { icon: string; label: string; blurb: string; cls: string }
> = {
  experimental: {
    icon: '\u{1F7E2}',
    label: 'DIRECT EXPERIMENTAL PRECEDENT',
    blurb:
      'This exact transformation, on these substrates, was found in the indexed experimental database.',
    cls: 'ev-experimental',
  },
  similar_experimental: {
    icon: '\u{1F7E1}',
    label: 'SIMILAR EXPERIMENTAL PRECEDENT',
    blurb:
      'Conditions observed in chemically similar reactions on different substrates. Not a precedent for this reaction.',
    cls: 'ev-similar',
  },
  predicted: {
    icon: '\u{1F535}',
    label: 'AI-PREDICTED CONDITIONS',
    blurb:
      'Generated by a prediction model. Not experimentally verified; nobody ran this.',
    cls: 'ev-predicted',
  },
  unavailable: {
    icon: '\u26AA',
    label: 'NO VERIFIED CONDITION EVIDENCE',
    blurb:
      'No suitable experimental evidence found in the indexed sources. Not a statement that none exists.',
    cls: 'ev-none',
  },
}

function EvidenceBadge({ level }: { level: EvidenceLevel }) {
  const e = EVIDENCE[level] ?? EVIDENCE.unavailable
  return (
    <span className={`ev-badge ${e.cls}`} title={e.blurb}>
      <span aria-hidden="true">{e.icon}</span> {e.label}
    </span>
  )
}

/** Badge plus the sentence that says what the badge actually claims. Shown
 *  wherever there is room for it, so the meaning never depends on a tooltip. */
function EvidenceClaim({ level }: { level: EvidenceLevel }) {
  const e = EVIDENCE[level] ?? EVIDENCE.unavailable
  return (
    <div className="ev-claim">
      <EvidenceBadge level={level} />
      <p className="muted small">{e.blurb}</p>
    </div>
  )
}

/** Renders the observed range alongside the median, so a single number never
 *  stands in for a spread of reported values. */
function valueText(v?: ConditionValue | null): string | null {
  if (!v) return null
  const unit = v.normalized_unit ?? v.unit ?? ''
  const suffix = unit ? ` ${unit}` : ''
  const main = `${v.normalized_value ?? v.value}${suffix}`
  if (v.minimum != null && v.maximum != null && v.minimum !== v.maximum) {
    return `${main} (observed ${v.minimum}\u2013${v.maximum}${suffix})`
  }
  return main
}

function names(list: ChemicalEntity[] | undefined, limit = 3): string | null {
  const out = (list ?? [])
    .slice(0, limit)
    .map((e) => e.name || e.smiles)
    .filter(Boolean)
  return out.length ? out.join(', ') : null
}

function CondRow({ label, value }: { label: string; value: string | null }) {
  if (!value) return null
  return (
    <div className="cond-row">
      <span className="cond-key">{label}</span>
      <span className="cond-val">{value}</span>
    </div>
  )
}

function getStructuralStatusDisplay(status?: ValidationStatus) {
  switch (status) {
    case 'MATCH': return { icon: '🟢', text: 'Match' }
    case 'PARTIAL_MATCH': return { icon: '🟡', text: 'Partial match' }
    case 'MISMATCH': return { icon: '🟠', text: 'Disagreement — requires review' }
    case 'MODEL_OUTPUT_INVALID': return { icon: '🔴', text: 'Invalid model output' }
    case 'MODEL_UNAVAILABLE': return { icon: '⚪', text: 'Validation unavailable' }
    case 'VALIDATION_ERROR':
    default: return { icon: '⚪', text: 'Validation error' }
  }
}

function getForwardStatusDisplay(status?: ValidationStatus) {
  switch (status) {
    case 'MATCH': return { icon: '🟢', text: 'Match' }
    case 'PARTIAL_MATCH': return { icon: '🟡', text: 'Partial match' }
    case 'MISMATCH': return { icon: '🟠', text: 'Forward-model disagreement — requires review' }
    case 'MODEL_OUTPUT_INVALID': return { icon: '🔴', text: 'Invalid model output' }
    case 'MODEL_UNAVAILABLE': return { icon: '⚪', text: 'Forward validation unavailable' }
    case 'VALIDATION_ERROR':
    default: return { icon: '⚪', text: 'Validation error' }
  }
}

function ReactionAssessment({ reaction }: { reaction: Reaction }) {
  const sVal = reaction.structural_validation
  const fVal = reaction.forward_validation
  const evidence = reaction.evidence
  const assessment = reaction.assessment
  
  const sDisplay = getStructuralStatusDisplay(sVal?.status)
  const fDisplay = getForwardStatusDisplay(fVal?.status)
  
  let eIcon = '⚪'
  let eText = 'No verified evidence'
  if (evidence) {
    if (evidence.evidence_level === 'experimental') { eIcon = '🟢'; eText = 'Direct experimental precedent' }
    else if (evidence.evidence_level === 'similar_experimental') { eIcon = '🟡'; eText = 'Similar experimental precedent' }
    else if (evidence.evidence_level === 'predicted') { eIcon = '🟠'; eText = 'Predicted' }
  }

  return (
    <div className="reaction-assessment">
      <div className="assessment-summary-row">
         <span>Structural consistency</span>
         <span>{sDisplay.icon} {sDisplay.text}</span>
      </div>
      <div className="assessment-summary-row">
         <span>Forward-model validation</span>
         <span>{fDisplay.icon} {fDisplay.text}</span>
      </div>
      <div className="assessment-summary-row">
         <span>Experimental evidence</span>
         <span>{eIcon} {eText}</span>
      </div>
      
      {assessment && (
        <>
          <hr style={{ margin: '12px 0', borderColor: 'var(--border)' }} />
          <div className="assessment-summary-row" style={{ fontWeight: 600 }}>
             <span>Why?</span>
          </div>
          <div className="muted small" style={{ marginTop: '4px' }}>
            {assessment.interpretation}
          </div>
          {assessment.flags && assessment.flags.length > 0 && (
            <div className="muted small" style={{ marginTop: '4px', color: '#ff9800' }}>
              Flags: {assessment.flags.map(f => f.replace(/_/g, ' ')).join(', ')}
            </div>
          )}
        </>
      )}

      <details style={{ marginTop: '16px' }}>
        <summary className="muted">Technical details</summary>
        <div className="assessment-details" style={{ marginTop: '8px' }}>
          <div className="assessment-section">
            <h4>Structural</h4>
            <div className="cond-row">
              <span className="cond-key">{sVal?.status || 'UNAVAILABLE'}</span>
            </div>
          </div>
          
          <div className="assessment-section">
            <h4>Forward model</h4>
            <div className="cond-row">
              <span className="cond-key">{fVal?.status || 'UNAVAILABLE'}</span>
            </div>
            {fVal?.model && <CondRow label="Model" value={fVal.model} />}
            {fVal?.predicted_products?.[0] && (
               <CondRow label="Top prediction" value={fVal.predicted_products[0]} />
            )}
            {fVal?.inference_time_ms != null && (
               <CondRow label="Inference" value={`${(fVal.inference_time_ms / 1000).toFixed(1)} s`} />
            )}
          </div>
          
          <div className="assessment-section">
            <h4>Experimental evidence</h4>
            {evidence && <ArrowConditions evidence={evidence} />}
          </div>
        </div>
      </details>
    </div>
  )
}

/** The compact block that sits on the reaction arrow. */
function ArrowConditions({ evidence }: { evidence: ReactionEvidence }) {
  const c = evidence.conditions
  const has =
    c &&
    (c.reagents?.length ||
      c.catalysts?.length ||
      c.solvents?.length ||
      c.temperature ||
      c.time)

  return (
    <div className="rstep-conditions">
      <EvidenceBadge level={evidence.evidence_level} />
      {has ? (
        <div className="cond-list">
          {evidence.evidence_level === 'similar_experimental' && (
            <p className="cond-qualifier">
              From similar reactions on different substrates — not this reaction.
            </p>
          )}
          <CondRow label="Reagents" value={names(c?.reagents)} />
          <CondRow label="Catalyst" value={names(c?.catalysts)} />
          <CondRow label="Solvent" value={names(c?.solvents)} />
          <CondRow label="Temp" value={valueText(c?.temperature)} />
          <CondRow label="Time" value={valueText(c?.time)} />
        </div>
      ) : (
        <p className="cond-empty">
          {evidence.reason ?? 'No match in the indexed evidence sources.'}
        </p>
      )}
    </div>
  )
}

function ConditionsTable({ c }: { c: ReactionConditions }) {
  return (
    <div className="cond-list">
      <CondRow label="Reagents" value={names(c.reagents, 6)} />
      <CondRow label="Catalysts" value={names(c.catalysts, 6)} />
      <CondRow label="Solvents" value={names(c.solvents, 6)} />
      <CondRow label="Temperature" value={valueText(c.temperature)} />
      <CondRow label="Time" value={valueText(c.time)} />
      <CondRow label="Pressure" value={valueText(c.pressure)} />
      <CondRow label="Reported yield" value={valueText(c.yield)} />
      <CondRow label="Workup" value={c.workup?.length ? c.workup.join('; ') : null} />
    </div>
  )
}

function PrecedentItem({ p }: { p: Precedent }) {
  const prov = p.provenance
  const citation = [prov?.journal, prov?.year].filter(Boolean).join(' ')

  return (
    <li className="precedent">
      <div className="precedent-head">
        <code>{p.reaction_id}</code>
        {p.match_type && <span className="tag">{p.match_type} match</span>}
        {p.similarity != null && (
          <span
            className="muted small"
            title="Chemical similarity between the two transformations. NOT a probability that this reaction will work."
          >
            similarity {p.similarity.toFixed(3)}
          </span>
        )}
      </div>

      {p.conditions && <ConditionsTable c={p.conditions} />}

      <div className="precedent-source">
        {prov?.title && <div className="precedent-title">{prov.title}</div>}
        <div className="muted small">
          {citation && <span>{citation} · </span>}
          {prov?.dataset_name && <span>dataset {prov.dataset_name} · </span>}
          {prov?.doi && <span>DOI {prov.doi}</span>}
          {prov?.patent_number && <span> · {prov.patent_number}</span>}
        </div>
        {/*  A link is shown only when the source itself supplied a URL. A DOI is
             never turned into a link by string-building - that produces an
             authoritative-looking link to the wrong paper. */}
        {prov?.url ? (
          <a href={prov.url} target="_blank" rel="noreferrer noopener">
            Open source ↗
          </a>
        ) : (
          prov?.doi && (
            <span className="muted small">
              No link supplied by the source record; DOI shown exactly as recorded.
            </span>
          )
        )}
      </div>
    </li>
  )
}

